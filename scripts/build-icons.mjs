// Builds a tiny icon font containing only the Bootstrap Icons the app uses.
// Run `npm run build:icons` after adding or removing a `bi-*` class in src/.
import fs from "node:fs";
import path from "node:path";
import subsetFont from "subset-font";

const root = path.resolve(import.meta.dirname, "..");
const iconsDir = path.join(root, "node_modules/bootstrap-icons/font");
const codepoints = JSON.parse(fs.readFileSync(path.join(iconsDir, "bootstrap-icons.json"), "utf8"));
const BACKSLASH = String.fromCharCode(92);
const NEWLINE = String.fromCharCode(10);

function sourceFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(full);
    return /\.(tsx?|jsx?)$/.test(entry.name) ? [full] : [];
  });
}

const used = new Set();
for (const file of sourceFiles(path.join(root, "src"))) {
  for (const match of fs.readFileSync(file, "utf8").matchAll(/\bbi-([a-z0-9-]+)\b/g)) {
    if (match[1] in codepoints) used.add(match[1]);
  }
}
const names = [...used].sort();
const text = names.map((n) => String.fromCodePoint(codepoints[n])).join("");

const source = fs.readFileSync(path.join(iconsDir, "fonts/bootstrap-icons.woff2"));
const subset = await subsetFont(source, text, { targetFormat: "woff2" });
fs.writeFileSync(path.join(root, "src/app/fonts/bootstrap-icons-subset.woff2"), subset);

const header = [
  "/* Generated by scripts/build-icons.mjs from Bootstrap Icons (MIT). Do not edit by hand. */",
  ".bi::before {",
  "  display: inline-block;",
  "  font-family: var(--font-icons), sans-serif;",
  "  font-style: normal;",
  "  font-weight: normal;",
  "  font-variant: normal;",
  "  text-transform: none;",
  "  line-height: 1;",
  "  vertical-align: -0.125em;",
  "  -webkit-font-smoothing: antialiased;",
  "  -moz-osx-font-smoothing: grayscale;",
  "}",
];
const rules = names.map((n) => `.bi-${n}::before { content: "${BACKSLASH}${codepoints[n].toString(16)}"; }`);
fs.writeFileSync(path.join(root, "src/app/icons.css"), [...header, ...rules, ""].join(NEWLINE));
console.log(`${names.length} icons, font ${(subset.length / 1024).toFixed(1)} KB (was ${(source.length / 1024).toFixed(0)} KB)`);
